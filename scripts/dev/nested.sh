#!/usr/bin/env bash
# Starts (or stops) a nested cosmic-comp instance for shell-host development.
#
# start (default):
#   1. snapshot the existing $XDG_RUNTIME_DIR/wayland-N sockets
#   2. launch `COSMIC_BACKEND=winit cosmic-comp --no-xwayland` with
#      XDG_CONFIG_HOME pointed at scripts/dev/xdg-config (seeded shortcuts +
#      theme), logging to scripts/dev/out/comp.log
#   3. wait up to 10s for a NEW wayland-N socket to appear
#   4. write scripts/dev/.nested-env (WAYLAND_DISPLAY + compositor pid)
#   5. run wayland-info against the new socket, save the globals list to
#      scripts/dev/out/globals.txt
#
# stop:
#   kills the compositor process THIS script started (pid recorded in
#   scripts/dev/.nested-env) and nothing else. Never touches the host
#   session or any other cosmic-comp process.
#
# Do NOT run cosmic-session nested: see scripts/dev/README.md.
#
# GPU: nested cosmic-comp (winit backend) can fail to create a GL/EGL
# context on NVIDIA. Set SILL_NESTED_GPU=amd to force the Mesa (AMD iGPU)
# EGL vendor and DRI_PRIME=1 as a fallback.
set -euo pipefail

DEV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT_DIR="$DEV_DIR/out"
ENV_FILE="$DEV_DIR/.nested-env"
LOG_FILE="$OUT_DIR/comp.log"
GLOBALS_FILE="$OUT_DIR/globals.txt"
XDG_CONFIG_SEED="$DEV_DIR/xdg-config"

mkdir -p "$OUT_DIR"

: "${XDG_RUNTIME_DIR:?XDG_RUNTIME_DIR must be set (run inside a login session)}"

cmd="${1:-start}"

list_wayland_sockets() {
  # Only real sockets (type S), never the *.lock files next to them.
  local f
  for f in "$XDG_RUNTIME_DIR"/wayland-*; do
    [ -e "$f" ] || continue
    case "$f" in
      *.lock) continue ;;
    esac
    [ -S "$f" ] || continue
    basename "$f"
  done
}

stop_nested() {
  if [ ! -f "$ENV_FILE" ]; then
    echo "nested.sh stop: no $ENV_FILE, nothing to stop."
    return 0
  fi

  # shellcheck disable=SC1090
  source "$ENV_FILE"

  if [ -z "${NESTED_COMPOSITOR_PID:-}" ]; then
    echo "nested.sh stop: $ENV_FILE has no NESTED_COMPOSITOR_PID, nothing to stop."
    rm -f "$ENV_FILE"
    return 0
  fi

  if kill -0 "$NESTED_COMPOSITOR_PID" 2>/dev/null; then
    echo "nested.sh stop: stopping cosmic-comp pid $NESTED_COMPOSITOR_PID (WAYLAND_DISPLAY=${WAYLAND_DISPLAY:-?})"
    kill "$NESTED_COMPOSITOR_PID" 2>/dev/null || true
    for _ in $(seq 1 20); do
      kill -0 "$NESTED_COMPOSITOR_PID" 2>/dev/null || break
      sleep 0.2
    done
    if kill -0 "$NESTED_COMPOSITOR_PID" 2>/dev/null; then
      echo "nested.sh stop: pid $NESTED_COMPOSITOR_PID did not exit, sending SIGKILL"
      kill -9 "$NESTED_COMPOSITOR_PID" 2>/dev/null || true
    fi
  else
    echo "nested.sh stop: pid $NESTED_COMPOSITOR_PID is already gone."
  fi

  rm -f "$ENV_FILE"
}

start_nested() {
  if [ -f "$ENV_FILE" ]; then
    # shellcheck disable=SC1090
    source "$ENV_FILE"
    if [ -n "${NESTED_COMPOSITOR_PID:-}" ] && kill -0 "$NESTED_COMPOSITOR_PID" 2>/dev/null; then
      echo "nested.sh: already running (pid $NESTED_COMPOSITOR_PID, WAYLAND_DISPLAY=${WAYLAND_DISPLAY:-?})."
      echo "Run 'scripts/dev/nested.sh stop' first."
      exit 1
    fi
  fi

  local before after new_socket
  before="$(list_wayland_sockets | sort)"

  local -a env_args=(
    "COSMIC_BACKEND=winit"
    "XDG_CONFIG_HOME=$XDG_CONFIG_SEED"
  )

  if [ "${SILL_NESTED_GPU:-}" = "amd" ]; then
    echo "nested.sh: SILL_NESTED_GPU=amd -> forcing Mesa EGL vendor + DRI_PRIME=1"
    env_args+=(
      "__EGL_VENDOR_LIBRARY_FILENAMES=/usr/share/glvnd/egl_vendor.d/50_mesa.json"
      "DRI_PRIME=1"
    )
  fi

  echo "nested.sh: starting cosmic-comp (log: $LOG_FILE)"
  : > "$LOG_FILE"
  env "${env_args[@]}" cosmic-comp --no-xwayland >>"$LOG_FILE" 2>&1 &
  local comp_pid=$!
  disown "$comp_pid" 2>/dev/null || true

  new_socket=""
  for _ in $(seq 1 50); do
    if ! kill -0 "$comp_pid" 2>/dev/null; then
      echo "nested.sh: cosmic-comp (pid $comp_pid) exited early. Log:"
      cat "$LOG_FILE" >&2
      exit 1
    fi
    after="$(list_wayland_sockets | sort)"
    new_socket="$(comm -13 <(echo "$before") <(echo "$after") | head -n1)"
    if [ -n "$new_socket" ]; then
      break
    fi
    sleep 0.2
  done

  if [ -z "$new_socket" ]; then
    echo "nested.sh: timed out after 10s waiting for a new wayland-N socket."
    echo "cosmic-comp log ($LOG_FILE):"
    cat "$LOG_FILE" >&2
    kill "$comp_pid" 2>/dev/null || true
    exit 1
  fi

  echo "nested.sh: nested compositor is up: WAYLAND_DISPLAY=$new_socket (pid $comp_pid)"

  cat > "$ENV_FILE" <<EOF
# generated by scripts/dev/nested.sh -- do not edit by hand
WAYLAND_DISPLAY=$new_socket
NESTED_COMPOSITOR_PID=$comp_pid
NESTED_XDG_CONFIG_HOME=$XDG_CONFIG_SEED
EOF

  echo "nested.sh: wrote $ENV_FILE"

  # A moment for the socket to accept connections before probing it.
  sleep 0.3

  if command -v wayland-info >/dev/null 2>&1; then
    echo "nested.sh: running wayland-info -> $GLOBALS_FILE"
    # A compositor that accepted the socket but never completes a client's first
    # roundtrip (e.g. its own winit-backend window never gets configured because the
    # HOST compositor is not mapping new client windows right now, such as a locked
    # session) would otherwise hang this script forever. Bound it and say so.
    wi_rc=0
    timeout 10 env WAYLAND_DISPLAY="$new_socket" wayland-info >"$GLOBALS_FILE" 2>&1 || wi_rc=$?
    if [ "$wi_rc" -ne 0 ]; then
      if [ "$wi_rc" -eq 124 ]; then
        echo "nested.sh: wayland-info did not complete within 10s (compositor accepted the" >&2
        echo "  socket but never answered a client). If the HOST session is locked or its" >&2
        echo "  display is in DPMS off, the winit backend's own window on the host never gets" >&2
        echo "  configured and cosmic-comp cannot render anything, including to other nested" >&2
        echo "  clients. Check: loginctl show-session <id> -p LockedHint, kscreen-doctor --dpms" >&2
        echo "  show. Unlock/wake the host session and re-run 'nested.sh stop' then 'start'." >&2
      else
        echo "nested.sh: wayland-info exited non-zero; see $GLOBALS_FILE" >&2
      fi
    fi
  else
    echo "nested.sh: wayland-info not found, skipping globals dump." >&2
  fi

  echo "nested.sh: ready. Source $ENV_FILE or use scripts/dev/run.sh to launch clients."
}

case "$cmd" in
  start)
    start_nested
    ;;
  stop)
    stop_nested
    ;;
  *)
    echo "usage: $(basename "$0") [start|stop]" >&2
    exit 2
    ;;
esac
